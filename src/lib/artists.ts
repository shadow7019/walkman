// The world's bands & artists registry — every major act across every genre,
// language and scene. Each entry drives an iTunes artist sweep that pulls that
// act's real songs (256 kbps AAC previews + full industry metadata) into the DB.
// Sweeps are resumable: every completed artist is logged in SyncLog.
export interface ArtistEntry {
  name: string
  genre: string
  language: string
  country: string // iTunes storefront used for the search
  limit: number // max songs to pull for this act
}

const E = (name: string, genre: string, language = 'English', country = 'US', limit = 80): ArtistEntry =>
  ({ name, genre, language, country, limit })

