// Merge everything; drop duplicate names (case-insensitive, accent-insensitive)
const dedupe = (arr: ArtistEntry[]) => {
  const seen = new Set<string>()
  return arr.filter((a) => {
    const k = a.name.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim()
    if (seen.has(k)) return false
    seen.add(k)
    return true
  })
}

